import type { Metadata } from 'next';
import { PartnerJoinForm } from '@/components/PartnerJoinForm';
import { PARTNER } from '@/config/partner';
import { ROUTES } from '@/config/site';

export const metadata: Metadata = { title: 'Партнерская программа' };

const first = Math.round(PARTNER.firstPurchaseRate * 100);
const repeat = Math.round(PARTNER.repeatPurchaseRate * 100);

/** Публичная часть партнерской программы. */
export default async function PartnerPage({
  searchParams,
}: {
  searchParams: Promise<{ login?: string }>;
}) {
  const { login } = await searchParams;

  return (
    <article>
      <h1>Партнерская программа</h1>

      {login === 'expired' && (
        <div className="dev-note">
          Ссылка для входа больше не работает: у нее истек срок. Оставьте почту ниже, придет новая.
        </div>
      )}

      <p className="lead">
        Если вы рекомендуете наши материалы коллегам или своим ученикам, мы делимся с вами частью
        того, что они принесли.
      </p>

      <h2>Сколько</h2>
      <ul>
        <li>
          <strong>{first} процентов</strong> с первой покупки человека, который пришел по вашей
          ссылке.
        </li>
        <li>
          <strong>{repeat} процентов</strong> со всех его следующих покупок, пожизненно.
        </li>
      </ul>
      <p>
        База расчета - фактически поступившая сумма, после скидок, если они были.
      </p>

      <h2>Как закрепляется человек</h2>
      <p>
        Первый партнер, по ссылке которого пришел человек, закреплен за ним навсегда. Если позже он
        перейдет по ссылке другого партнера, закрепление не изменится. Это правило работает в обе
        стороны: чужого ученика у вас не заберут, но и чужого вы не получите.
      </p>
      <p>
        Код из ссылки хранится в браузере человека {PARTNER.cookieDays} дней. Закрепление
        происходит в момент первой покупки.
      </p>

      <h2>Когда выплата</h2>
      <p>
        Вознаграждение появляется в кабинете сразу после оплаты, в статусе «ожидает
        подтверждения». В статус «к выплате» оно переходит после того, как продукт завершен: так мы
        не выплачиваем вознаграждение с покупки, по которой может быть возврат.
      </p>

      <h2>Кто может подключиться</h2>
      <p>
        Любой человек, который знаком с нашими материалами: вокальный педагог, руководитель студии,
        коллега из смежной области. Ограничений по числу учеников нет.
      </p>

      <h2>Налоги</h2>
      <p>
        Выплаты идут только тем, кто может принять их легально: самозанятым или ИП. Налоги партнер
        платит сам. 【порядок оформления: договор, акт, чек - уточняет заказчик】
      </p>

      <h2>Подключиться</h2>
      <p>
        Оставьте почту, и мы пришлем на нее партнерский код и ссылку для входа в кабинет. Пароля
        нет: вход всегда по ссылке из письма.
      </p>
      <PartnerJoinForm />

      <p className="muted" style={{ marginTop: 32 }}>
        Уже подключены? Ссылка для входа приходит на почту. Если она перестала работать, оставьте
        почту еще раз - придет новая. Кабинет находится по адресу {ROUTES.partnerCabinet}.
      </p>
    </article>
  );
}
